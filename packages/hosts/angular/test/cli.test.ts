import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { build, checkOverwriteGuard } from "../src/build.ts";
import { runCli } from "../src/cli.ts";
import { type AngularConfig, readAngularConfig } from "../src/config.ts";
import { discoverFiles } from "../src/discover.ts";

let projectDir: string;

function writeProject(files: Record<string, string>): void {
  for (const [path, content] of Object.entries(files)) {
    const full = join(projectDir, path);
    mkdirSync(join(full, ".."), { recursive: true });
    writeFileSync(full, content, "utf8");
  }
}

beforeEach(() => {
  projectDir = mkdtempSync(join(tmpdir(), "mx-angular-test-"));
});

afterEach(() => {
  rmSync(projectDir, { recursive: true, force: true });
});

describe("readAngularConfig", () => {
  it("applies A3's defaults when mx.angular is absent", () => {
    writeProject({ "package.json": JSON.stringify({ name: "x" }) });
    const config = readAngularConfig(projectDir);
    expect(config).toEqual({
      include: [],
      pageExtension: ".html",
      tagExtension: ".ts",
      ngExtension: ".ts",
      tagSelectorPrefix: "mx-",
      onError: "keep-last",
    });
  });

  it("reads explicit values", () => {
    writeProject({
      "package.json": JSON.stringify({
        name: "x",
        mx: {
          host: "angular",
          angular: {
            include: ["src/**/*.mx"],
            pageExtension: ".ng.html",
            tagExtension: ".tag.ts",
            tagSelectorPrefix: "app-",
            onError: "delete",
          },
        },
      }),
    });
    const config = readAngularConfig(projectDir);
    expect(config).toEqual({
      include: ["src/**/*.mx"],
      pageExtension: ".ng.html",
      tagExtension: ".tag.ts",
      ngExtension: ".ts",
      tagSelectorPrefix: "app-",
      onError: "delete",
    });
  });

  it("rejects an invalid onError value", () => {
    writeProject({
      "package.json": JSON.stringify({
        mx: { angular: { onError: "nope" } },
      }),
    });
    expect(() => readAngularConfig(projectDir)).toThrow(/onError/);
  });

  it("rejects an unrecognized key, positioned against package.json", () => {
    writeProject({
      "package.json": JSON.stringify({
        mx: { angular: { typo: true } },
      }),
    });

    let caught: unknown;
    try {
      readAngularConfig(projectDir);
    } catch (err) {
      caught = err;
    }

    expect(caught).toBeInstanceOf(Error);
    const err = caught as {
      message: string;
      line?: number;
      column?: number;
      file?: string;
    };
    expect(err.message).toMatch(/`mx\.angular\.typo` is not a recognized key/);
    expect(err.line).toBe(1);
    expect(err.column).toBe(0);
    expect(err.file).toBe(join(projectDir, "package.json"));
  });
});


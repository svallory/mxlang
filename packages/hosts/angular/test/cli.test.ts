describe("build: page header lists the event invoker members (decision 117)", () => {
  const project = {
    mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
  };

  it("adds the exact paste text to the header when the page binds a handler, and the map still lines up", () => {
    writeProject({
      "package.json": JSON.stringify(project),
      "src/form.mx": "<button onClick=cancel>x</button>",
    });

    expect(build(projectDir).ok).toBe(true);
    const html = readFileSync(join(projectDir, "src/form.html"), "utf8");
    const lines = html.split("\n");
    expect(lines[0]).toBe(
      "<!-- Generated by @mxlang/angular from form.mx. Do not edit. -->",
    );
    const members = EVENT_HELPER_MEMBERS.map((m) => `\`${m.trim()}\``).join(
      " and ",
    );
    expect(lines[1]).toBe(
      `<!-- Add to the component class in form.ts: ${members}, or extend \`MxHandlers\` (or \`MxHandlersMixin(Base)\` when the class already extends another) from "@mxlang/angular/runtime" -->`,
    );
    expect(lines[2]).toBe(
      '<button (click)="__mxOn(cancel, this, $event)">x</button>',
    );
    // A comment must not end early: no `-->` inside the member text.
    expect(lines[1]?.indexOf("-->")).toBe(
      lines[1]?.length ? lines[1].length - 3 : -1,
    );
    // The sidecar is shifted by both header lines.
    const map = JSON.parse(
      readFileSync(join(projectDir, "src/form.html.map"), "utf8"),
    );
    expect(map.mappings.startsWith(";;")).toBe(true);
  });

  it("adds no members line when the page binds no handler", () => {
    writeProject({
      "package.json": JSON.stringify(project),
      "src/plain.mx": "<div>x</div>",
    });

    expect(build(projectDir).ok).toBe(true);
    const html = readFileSync(join(projectDir, "src/plain.html"), "utf8");
    expect(html).not.toContain("__mxOn");
    expect(html.split("\n")[1]).toBe("<div>x</div>");
  });
});

describe("build: tag routing", () => {
  it("routes a tags/-discovered .mx file as a tag, not a page, even outside include", () => {
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/pages/**/*.mx"] } },
      }),
      "src/pages/home.mx": "<div>home</div>",
      "src/tags/badge.mx": "<span>${input.text}</span>",
    });

    const result = build(projectDir);

    expect(result.errors).toEqual([]);
    // A tag compiles to a `.ts` component module, never a `.html` template:
    // an Angular component is a class with a decorator (A3's two output
    // kinds), so the page extension would be the wrong artifact entirely.
    expect(existsSync(join(projectDir, "src/tags/badge.html"))).toBe(false);
    const module = readFileSync(join(projectDir, "src/tags/badge.ts"), "utf8");
    expect(module).toContain(
      "// Generated by @mxlang/angular from badge.mx. Do not edit.",
    );
    expect(module).toContain('selector: "mx-badge"');
    expect(module).toContain("export class Badge");

    // The page file still compiles fine.
    expect(existsSync(join(projectDir, "src/pages/home.html"))).toBe(true);
  });

  it("warns once when include and the tag index both claim a path", () => {
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/tags/badge.mx": "<span>${input.text}</span>",
    });

    const result = build(projectDir);

    expect(result.warnings).toHaveLength(1);
    expect(result.warnings[0]?.file).toMatch(/badge\.mx$/);
    expect(result.warnings[0]?.message).toMatch(/tag index/);
  });

  it("resolves a discovered lowercase tag (sidecar transform) when compiling a page that calls it", () => {
    // `<badge/>` is lowercase: with no discovered custom tag registered,
    // @mxlang/core's lower.ts treats an unbound lowercase tag as a hard
    // "unknown tag" compile error (it is never mistaken for an HTML
    // element) — compiling this page without threading the discovered tag
    // index into compile() would fail outright. A sidecar `transform`
    // returning plain IR (a macro), rather than a bare template, is what
    // this test can exercise directly: a *template* tag call goes through
    // a different, already-known-limited path (an injected import node
    // this host's step-1 emitter rejects — see the design note's A3/A5;
    // out of scope here).
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/pages/**/*.mx"] } },
      }),
      "src/pages/home.mx": "<badge/>",
      "src/tags/badge.tag.ts": `
        export default {
          transform(call, ctx) {
            return [ctx.build.text("BADGE")];
          },
        };
      `,
    });

    const result = build(projectDir);

    expect(result.errors.filter((e) => e.file.endsWith("home.mx"))).toEqual([]);
    const html = readFileSync(join(projectDir, "src/pages/home.html"), "utf8");
    expect(html).toContain("BADGE");
  });

  it("reports a tag template's own compile error against the tag file, not the caller (A5)", () => {
    // `badge.mx` here is a *template* tag (no sidecar) with a body error
    // core catches during its own tag-unit metadata compile
    // (template-tag.ts's metadataForTemplate) — a construct core itself
    // rejects (a `<for>` needing tag params), not an Angular-emitter
    // rejection. core's TranslateError carries `file: badge.mx` for
    // exactly this case (A5); build.ts must report against that file, not
    // home.mx, which merely called it.
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/pages/**/*.mx"] } },
      }),
      "src/pages/home.mx": "<badge/>",
      "src/tags/badge.mx": "<for from=1 to=10><div>x</div></for>",
    });

    const result = build(projectDir);

    expect(result.ok).toBe(false);
    const tagError = result.errors.find((e) => e.file.endsWith("badge.mx"));
    expect(tagError).toBeDefined();
    expect(result.errors.some((e) => e.file.endsWith("home.mx"))).toBe(false);
  });

  it("does not claim an mx.tags entry scoped to a different host", () => {
    writeProject({
      "package.json": JSON.stringify({
        mx: {
          host: "angular",
          angular: { include: ["src/**/*.mx"] },
          tags: [{ dir: "widgets", hosts: ["solid"] }],
        },
      }),
      "widgets/gadget.mx": "<span>gadget</span>",
    });

    const { files } = discoverFiles(projectDir, readAngularConfig(projectDir));

    expect(files.some((f) => f.path.endsWith("gadget.mx"))).toBe(false);

    // build() only ever writes beside a page's own include match, so no
    // output for the excluded tag either.
    build(projectDir);
    expect(existsSync(join(projectDir, "widgets/gadget.html"))).toBe(false);
  });

  it("leaves an unmatched mx.tags host unresolved under its own-only lookup", () => {
    // PR 3 round-2 ruling: own-only lookups cannot validate peer names.
    // The full-registry discovery/build/watch paths are pinned separately.
    writeProject({
      "package.json": JSON.stringify({
        mx: {
          host: "angular",
          angular: { include: ["src/**/*.mx"] },
          tags: [{ dir: "widgets", hosts: ["bogus"] }],
        },
      }),
      "src/page.mx": "<div>no call</div>",
      "widgets/gadget.mx": "<span>gadget</span>",
    });

    const result = build(projectDir);

    expect(
      result.warnings.some(
        (w) => /bogus/.test(w.message) && /package\.json$/.test(w.file),
      ),
    ).toBe(false);
  });

  it("claims an mx.tags entry scoped to angular, or with no hosts restriction at all", () => {
    writeProject({
      "package.json": JSON.stringify({
        mx: {
          host: "angular",
          angular: { include: ["src/**/*.mx"] },
          tags: [
            { dir: "widgets-scoped", hosts: ["angular"] },
            { dir: "widgets-unscoped" },
          ],
        },
      }),
      "widgets-scoped/gadget.mx": "<span>gadget</span>",
      "widgets-unscoped/thing.mx": "<span>thing</span>",
    });

    const { files } = discoverFiles(projectDir, readAngularConfig(projectDir));

    expect(
      files.some((f) => f.path.endsWith("gadget.mx") && f.kind === "tag"),
    ).toBe(true);
    expect(
      files.some((f) => f.path.endsWith("thing.mx") && f.kind === "tag"),
    ).toBe(true);
  });

  it("discovers a tags/ directory two levels below a project-root-owned path", () => {
    // proj/a has no package.json; proj/a/b doesn't either. A tags/ dir
    // under proj/a/b must still be discovered as the project root's own
    // tag index — the walk must not stop merely because it passed through
    // non-package directories on the way.
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["a/b/pages/**/*.mx"] } },
      }),
      "a/b/pages/home.mx": "<div>home</div>",
      "a/b/tags/y.mx": "<span>y</span>",
    });

    const { files } = discoverFiles(projectDir, readAngularConfig(projectDir));

    const tag = files.find((f) => f.path.endsWith("a/b/tags/y.mx"));
    expect(tag).toBeDefined();
    expect(tag?.kind).toBe("tag");

    // Misrouted as a page would have emitted a/b/tags/y.html — must not.
    build(projectDir);
    expect(existsSync(join(projectDir, "a/b/tags/y.html"))).toBe(false);
  });

  it("does not descend into a nested package's own tags/ directory", () => {
    // @mxlang/core's discoverProjectTags (packages/core/src/scan.ts) treats
    // any directory holding its own package.json, other than the project
    // root, as a separate project's boundary and never descends into it —
    // its tags belong to *its* project, not this one. This is a behavior
    // change from the angular watcher's own former walk, which continued
    // past a nested package.json (only switching which mx.tags governed
    // tags found underneath); adopting core's shared enumerator means a
    // nested package's tags/ directory is no longer discovered here.
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["a/b/pages/**/*.mx"] } },
      }),
      "a/b/package.json": JSON.stringify({ name: "nested" }),
      "a/b/pages/home.mx": "<div>home</div>",
      "a/b/tags/y.mx": "<span>y</span>",
    });

    const { files } = discoverFiles(projectDir, readAngularConfig(projectDir));

    const tag = files.find((f) => f.path.endsWith("a/b/tags/y.mx"));
    expect(tag).toBeUndefined();
  });

  it("watches an empty tags/ directory and a tags/ directory whose names were all shadowed", () => {
    // tagDirectories must come from every tags/ directory core's walk
    // visited, not only from a surviving DiscoveredTag's own sourceDir:
    // neither an empty directory nor one whose every name lost to a
    // shallower tags/ directory of the same name leaves a DiscoveredTag
    // behind, but a watcher still needs to know about both.
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/home.mx": "<div>home</div>",
      "tags/icon.mx": "<span>icon</span>",
      "src/tags/icon.mx": "<span>shadowed</span>",
    });
    mkdirSync(join(projectDir, "empty/tags"), { recursive: true });

    const { tagDirectories } = discoverFiles(
      projectDir,
      readAngularConfig(projectDir),
    );

    expect(tagDirectories).toContain(join(projectDir, "tags"));
    expect(tagDirectories).toContain(join(projectDir, "src/tags"));
    expect(tagDirectories).toContain(join(projectDir, "empty/tags"));
  });

  it("warns when a tags/ directory exists but cannot be read", () => {
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/home.mx": "<div>home</div>",
    });
    const tagsDir = join(projectDir, "tags");
    mkdirSync(tagsDir, { recursive: true });
    chmodSync(tagsDir, 0o000);

    try {
      // root running the suite ignores permission bits entirely, so the
      // directory stays readable and there is nothing to assert.
      const stillReadable = (() => {
        try {
          readdirSync(tagsDir);
          return true;
        } catch {
          return false;
        }
      })();
      if (stillReadable) return;

      const { diagnostics } = discoverFiles(
        projectDir,
        readAngularConfig(projectDir),
      );

      expect(
        diagnostics.some(
          (d) => d.file === tagsDir && d.message.includes("could not read"),
        ),
      ).toBe(true);
    } finally {
      chmodSync(tagsDir, 0o755);
    }
  });

  it("reports a broken package.json exactly once, from discoverProjectTags's own manifest cache", () => {
    // excludedMxTagsDirs (discover.ts) re-reads package.json itself and
    // swallows a JSON.parse failure silently. This proves the guarantee
    // that silence relies on: discoverProjectTags's own readManifest
    // already reads and diagnoses the same file, so a second diagnostic
    // from excludedMxTagsDirs's catch would double-warn for one broken
    // file. Called directly with a hand-built AngularConfig, bypassing
    // readAngularConfig (which reads package.json independently and would
    // throw on this same malformed JSON before discoverFiles ever runs —
    // see the next test for that path's own contract).
    writeProject({ "src/home.mx": "<div>home</div>" });
    writeFileSync(join(projectDir, "package.json"), "{ broken", "utf8");

    const config: AngularConfig = {
      include: ["src/**/*.mx"],
      pageExtension: ".html",
      tagExtension: ".ts",
      ngExtension: ".ts",
      tagSelectorPrefix: "mx-",
      onError: "keep-last",
      diagnostics: "idle",
    };
    const { diagnostics } = discoverFiles(projectDir, config);

    const packageJson = join(projectDir, "package.json");
    const matching = diagnostics.filter((d) => d.file === packageJson);
    expect(matching).toHaveLength(1);
    expect(matching[0]?.message).toContain("could not be parsed as JSON");
  });

  it("an invalid mx.tags shape is a fatal, positioned error — not a silently continued build", () => {
    // discoverProjectTags's own indexMxTagsEntries calls normalizeMxTags
    // uncaught: an invalid mx.tags entry throws a TranslateError through
    // discoverFiles rather than being recorded as a diagnostic. This is
    // deliberate, matching readAngularConfig's own fatal-on-bad-config
    // contract elsewhere in this file ("rejects an unrecognized key,
    // positioned against package.json") — silently continuing with an
    // incomplete tag index would be worse than failing loud. excludedMxTagsDirs's
    // own normalizeMxTags catch is therefore never reached on this path:
    // discoverProjectTags throws before excludedMxTagsDirs runs at all.
    writeProject({
      "package.json": JSON.stringify({
        mx: {
          host: "angular",
          angular: { include: ["src/**/*.mx"] },
          tags: [{ dir: "tags", hosts: "not-an-array" }],
        },
      }),
      "src/home.mx": "<div>home</div>",
    });

    expect(() =>
      discoverFiles(projectDir, readAngularConfig(projectDir)),
    ).toThrow(/mx\.tags\[0\]\.hosts.*must be an array of strings/);
  });
});


describe("mx-angular map", () => {
  /** Runs `mx-angular map <arg>`, capturing what it printed. */
  function runMapCli(arg: string): {
    exitCode: number | Promise<number>;
    logs: string[];
  } {
    const logs: string[] = [];
    const originalLog = console.log;
    console.log = (msg: string) => logs.push(msg);
    try {
      return { exitCode: runCli(["map", arg]), logs };
    } finally {
      console.log = originalLog;
    }
  }

  it("resolves an emitted position back to its line and column in the .mx", () => {
    // Multi-line on both sides: the expression is on source line 3, so a
    // resolver that ignored line structure would answer line 1 here.
    const source = "<div>\n  <p>x</p>\n  <p>${user.name}</p>\n</div>\n";
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/greeting.mx": source,
    });
    build(projectDir);

    // Ask about the emitted `user.name`, wherever the emitter put it.
    const emitted = readFileSync(join(projectDir, "src/greeting.html"), "utf8");
    const at = emitted.indexOf("user.name");
    const before = emitted.slice(0, at);
    const line = before.split("\n").length;
    const column = at - (before.lastIndexOf("\n") + 1) + 1;

    const { exitCode, logs } = runMapCli(
      `${join(projectDir, "src/greeting.html")}:${line}:${column}`,
    );
    expect(exitCode).toBe(0);
    // Line 3, printed column 8 (offset 7): two spaces, `<p>`, `${`.
    expect(source.split("\n")[2]?.slice(7)).toBe("user.name}</p>");
    expect(logs).toEqual(["greeting.mx:3:8"]);
  });

  it("says so when the position came from no source text", () => {
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/greeting.mx": "<div>${user.name}</div>",
    });
    build(projectDir);

    // Printed column 1 is the `<`: generated punctuation, not source text.
    const { exitCode, logs } = runMapCli(
      `${join(projectDir, "src/greeting.html")}:1:1`,
    );
    expect(exitCode).toBe(0);
    expect(logs).toEqual([
      "greeting.mx",
      "that position came from no source text (generated punctuation)",
    ]);
  });

  it("does not fabricate a position for punctuation *after* a mapped run", () => {
    // The bug this pins: a v3 segment marks where a run starts and the run
    // extends to the next segment, so without a terminator at each run's end
    // every byte after the last expression -- `</div>` here, to the end of
    // the line -- resolved to that expression's source position.
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/greeting.mx": "<div>${user.name}</div>",
    });
    build(projectDir);

    const emitted = readFileSync(join(projectDir, "src/greeting.html"), "utf8");
    // Somewhere inside the trailing `</div>`, past the end of `user.name`.
    const at = emitted.lastIndexOf("</div>") + 2;
    const before = emitted.slice(0, at);
    const line = before.split("\n").length;
    const column = at - (before.lastIndexOf("\n") + 1) + 1;

    const { exitCode, logs } = runMapCli(
      `${join(projectDir, "src/greeting.html")}:${line}:${column}`,
    );
    expect(exitCode).toBe(0);
    expect(logs).toEqual([
      "greeting.mx",
      "that position came from no source text (generated punctuation)",
    ]);
  });

  it("says so when the sidecar carries no mappings at all", () => {
    // A text-only template derives nothing from source, so its map is empty.
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/greeting.mx": "<div>hi</div>",
    });
    build(projectDir);

    const { exitCode, logs } = runMapCli(
      `${join(projectDir, "src/greeting.html")}:1:1`,
    );
    expect(exitCode).toBe(0);
    expect(logs).toEqual([
      "greeting.mx",
      "no fine-grained mapping in this sidecar (mappings empty)",
    ]);
  });

  it("rejects a 0-based column rather than reinterpreting it", () => {
    // The guard `parseMapArg` adds. Every other row in this suite was
    // re-pointed to a 1-based input, which would leave this branch
    // uncovered: delete it and the whole `mx-angular map` suite still passes.
    // A `0` column is what the sidecar uses, so accepting one silently would
    // land the reader one byte left of the position an editor shows.
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/greeting.mx": "<div>\n  <p>${user.name}</p>\n</div>\n",
    });
    build(projectDir);

    const errors: string[] = [];
    const originalError = console.error;
    console.error = (msg: string) => errors.push(msg);
    try {
      expect(
        runCli(["map", `${join(projectDir, "src/greeting.html")}:2:0`]),
      ).toBe(1);
      expect(
        runCli(["map", `${join(projectDir, "src/greeting.html")}:0:1`]),
      ).toBe(1);
    } finally {
      console.error = originalError;
    }
    expect(errors).toHaveLength(2);
    for (const message of errors) {
      expect(message).toContain(
        "invalid position: line and column must be 1-based (at least 1)",
      );
    }
  });

  it("rejects a position it cannot read as numbers at all", () => {
    // `Number.isInteger`, not just `>= 1`: the `\d+` groups cannot be `NaN`
    // while the pattern holds, but `NaN < 1` is false, so a bare `< 1` check
    // would let a non-integer through if the pattern ever loosened.
    const originalError = console.error;
    const errors: string[] = [];
    console.error = (msg: string) => errors.push(msg);
    try {
      for (const arg of [
        "a.html:1:",
        "a.html:1:x",
        "a.html::1",
        "a.html:1:-2",
      ]) {
        expect(runCli(["map", arg])).toBe(1);
      }
    } finally {
      console.error = originalError;
    }
    expect(errors).toHaveLength(4);
    // Each is rejected — by the shape regex or the 1-based guard, both of
    // which exit non-zero with a message naming the position.
    expect(
      errors.every((message) => message.includes("invalid position")),
    ).toBe(true);
  });

  it("fails with a clear message when no sidecar exists", () => {
    const originalError = console.error;
    const errors: string[] = [];
    console.error = (msg: string) => errors.push(msg);
    try {
      const exitCode = runCli([
        "map",
        `${join(projectDir, "src/missing.html")}:1:1`,
      ]);
      expect(exitCode).toBe(1);
    } finally {
      console.error = originalError;
    }
    expect(errors[0]).toMatch(/could not read/);
  });
});


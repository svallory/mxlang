describe("build: .ng.mx round 2 review", () => {
  it("shifts the .map by the generated header, so positions are not off by one", () => {
    // The map is generated over the module alone, then the header is
    // prepended to the file — so without a shift every generated line the
    // map describes sits one line higher than where it actually is, and
    // `mx-angular map` is wrong for every `.ng.mx`.
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/x.component.ng.mx": [
        'import { Component } from "@angular/core";',
        "",
        "@Component({",
        '  selector: "app-x",',
        "  template: <div>",
        "    <p>${first}</p>",
        "    <p>${second}</p>",
        "  </div>,",
        "})",
        "export class XComponent { first = 1; second = 2; }",
      ].join("\n"),
    });

    expect(build(projectDir).errors).toEqual([]);

    const output = join(projectDir, "src/x.component.ts");
    const emitted = readFileSync(output, "utf8").split("\n");
    const map = JSON.parse(readFileSync(`${output}.map`, "utf8"));

    // One `;` per header line, so mapping line N describes emitted line N.
    const headerLines = emitted.filter((l) =>
      l.startsWith("// Generated by @mxlang/angular"),
    ).length;
    expect(headerLines).toBeGreaterThan(0);
    expect(map.mappings.startsWith(";".repeat(headerLines))).toBe(true);

    // The header's own lines map to nothing, which is the point.
    const lines = map.mappings.split(";");
    for (let i = 0; i < headerLines; i++) expect(lines[i]).toBe("");
  });

  it("rejects a .ng.mx inside a tags/ directory", () => {
    // Routed as a tag it reached the tag compiler and failed with a nonsense
    // error about its `@Component` decorator instead of saying what is wrong.
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/tags/bad.component.ng.mx": [
        'import { Component } from "@angular/core";',
        '@Component({ selector: "app-bad", template: <p>x</p> })',
        "export class BadComponent {}",
      ].join("\n"),
    });

    const result = build(projectDir);

    expect(
      result.warnings.some((w) =>
        /a `\.ng\.mx` file is a component module, not a tag/.test(w.message),
      ),
    ).toBe(true);
    // And no tag module written beside it.
    expect(existsSync(join(projectDir, "src/tags/bad.component.ts"))).toBe(
      false,
    );
  });

  it("diagnoses a .ng.mx under tags/ without dropping other tags directories", () => {
    writeProject({
      "package.json": JSON.stringify({
        mx: {
          host: "angular",
          angular: { include: ["src/**/*.mx"] },
          tags: [{ dir: "src/tags" }, { dir: "src/other-tags" }]
        },
      }),
      "src/page.mx": "<div><good/><fine/></div>",
      "src/tags/bad.component.ng.mx": [
        'import { Component } from "@angular/core";',
        '@Component({ selector: "app-bad", template: <p>x</p> })',
        "export class BadComponent {}",
      ].join("\n"),
      "src/tags/good.mx": "<p>good</p>",
      "src/other-tags/fine.mx": "<p>fine</p>",
    });

    const result = build(projectDir);

    expect(
      result.warnings.some((w) =>
        /a `\.ng\.mx` file is a component module, not a tag/.test(w.message),
      ),
    ).toBe(true);

    expect(existsSync(join(projectDir, "src/tags/bad.component.ts"))).toBe(false);
    expect(existsSync(join(projectDir, "src/tags/good.ts"))).toBe(true);
    expect(existsSync(join(projectDir, "src/other-tags/fine.ts"))).toBe(true);
  });
});

describe("build: .ng.mx routing", () => {
  it("compiles a .ng.mx to <basename>.ts beside it, with the header, guard and map", () => {
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/x.component.ng.mx": [
        'import { Component } from "@angular/core";',
        "",
        "@Component({",
        '  selector: "app-x",',
        "  template: <div>hi ${name}</div>,",
        "})",
        "export class XComponent { name = 'a'; }",
      ].join("\n"),
    });

    const result = build(projectDir);

    expect(result.errors).toEqual([]);
    // Both extension segments come off: `x.component.ts`, the name Angular
    // expects beside the source — not `x.component.ng.ts`.
    const output = join(projectDir, "src/x.component.ts");
    expect(existsSync(output)).toBe(true);
    // Never the page route's `.html`: a `.ng.mx` emits a whole module.
    expect(existsSync(join(projectDir, "src/x.component.html"))).toBe(false);

    const module = readFileSync(output, "utf8");
    expect(module).toContain(
      "// Generated by @mxlang/angular from x.component.ng.mx. Do not edit.",
    );
    expect(module).toContain("template: `<div>hi {{ name }}</div>`");
    expect(module).toContain("export class XComponent");

    const map = JSON.parse(readFileSync(`${output}.map`, "utf8"));
    expect(map.version).toBe(3);
    expect(map.sources).toEqual(["x.component.ng.mx"]);
  });

  it("refuses to overwrite a hand-written module at the output path", () => {
    writeProject({
      "package.json": JSON.stringify({
        mx: { host: "angular", angular: { include: ["src/**/*.mx"] } },
      }),
      "src/x.component.ng.mx": [
        'import { Component } from "@angular/core";',
        '@Component({ selector: "app-x", template: <p>hi</p> })',
        "export class XComponent {}",
      ].join("\n"),
      // A module MX did not generate: no header.
      "src/x.component.ts": "export class XComponent {}\n",
    });

    const result = build(projectDir);

    expect(result.ok).toBe(false);
    expect(result.errors[0]?.message).toMatch(/refusing to overwrite/);
    // The hand-written file is untouched.
    expect(readFileSync(join(projectDir, "src/x.component.ts"), "utf8")).toBe(
      "export class XComponent {}\n",
    );
  });
});

